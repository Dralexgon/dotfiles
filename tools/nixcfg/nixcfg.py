def caelestia_scheme() -> tuple[bool, dict[str, str]] | None:
    """Whether the Caelestia palette is dark, and its colors as #rrggbb."""
    try:
        scheme = json.loads(CAELESTIA_SCHEME.read_text())
        colours = {k: f"#{v}" for k, v in scheme["colours"].items()}
        return scheme.get("mode", "dark") == "dark", colours
    except (OSError, KeyError, ValueError, AttributeError):
        return None


def caelestia_theme() -> Theme | None:
    scheme = caelestia_scheme()
    if not scheme:
        return None
    dark, c = scheme
    try:
        return Theme(
            name="caelestia",
            dark=dark,
            primary=c["primary"],
            secondary=c["secondary"],
            accent=c["tertiary"],
            error=c["error"],
            warning=c.get("term3", c["tertiary"]),
            success=c.get("term2", c["secondary"]),
            foreground=c["onSurface"],
            background=c["background"],
            surface=c["surfaceContainerLow"],
            panel=c["surfaceContainer"],
        )
    except KeyError:
        return None


def terminal_palette(theme: Theme) -> str:
    """Escape codes giving the terminal the colors of a Textual theme.

    OSC 10/11 set the default foreground and background, OSC 4 the 16 ANSI
    colors (from Caelestia's term0-15, when there are some). kitty and tmux
    both understand them; TERMINAL_PALETTE_RESET puts the terminal's back.
    """
    codes = []
    scheme = caelestia_scheme()
    if scheme:
        codes += [f"\033]4;{i};{scheme[1][f'term{i}']}\033\\"
                  for i in range(16) if f"term{i}" in scheme[1]]
    if theme.foreground:
        codes.append(f"\033]10;{theme.foreground}\033\\")
    if theme.background:
        codes.append(f"\033]11;{theme.background}\033\\")
    # Clears the screen so it is painted with the new background.
    return "".join(codes) + "\033[2J\033[H"


TERMINAL_PALETTE_RESET = "\033]104\033\\\033]110\033\\\033]111\033\\"


def list_hosts() -> list[str]:
    return sorted(p.parent.name for p in HOSTS_DIR.glob("*/configuration.nix"))


def list_modules() -> list[str]:
    return sorted(
        p.relative_to(MODULES_DIR).with_suffix("").as_posix()
        for p in MODULES_DIR.rglob("*.nix")
    )


# nixos/core.nix, imported by every host: shown as an always-on module, so
# its packages can be toggled like any module's.
CORE = "core"


# nixos/hosts/<host>/configuration.nix, shown as an always-on module of its
# host (right after core), so the host's own file can be browsed and edited.
HOST_PREFIX = "hosts/"


def host_module(host: str) -> str:
    return f"{HOST_PREFIX}{host}"


def is_host_module(name: str) -> bool:
    return name.startswith(HOST_PREFIX)


def is_pinned(name: str) -> bool:
    """core and the host's configuration: always on, can't be deleted."""
    return name == CORE or is_host_module(name)


def module_path(name: str) -> Path:
    if name == CORE:
        return DOTFILES / "nixos" / "core.nix"
    if is_host_module(name):
        return host_path(name.removeprefix(HOST_PREFIX))
    return MODULES_DIR / f"{name}.nix"


def module_entries(name: str) -> list[modfile.Entry]:
    try:
        return modfile.entries(module_path(name).read_text())
    except OSError:
        return []


# A folder with a core.nix is a group (see hostfile.py): its core
# switches the whole group, and each submodule is toggled on its own.
def group_core(name: str) -> str | None:
    """The core of the group a submodule is in ("epita/c" -> "epita/core")."""
    folder, sep, _ = name.rpartition("/")
    core = f"{folder}/core"
    if not sep or name == core or not module_path(core).exists():
        return None
    return core


def is_group(name: str) -> bool:
    return name.endswith("/core") and module_path(name).exists()


def is_active(name: str, enabled: list[str]) -> bool:
    if is_pinned(name):
        return True
    core = group_core(name)
    return name in enabled and (core is None or core in enabled)


def display_key(name: str) -> tuple:
    """Sort groups by folder name, with their submodules right after them
    (and core.nix first)."""
    if is_pinned(name):
        return ("", False, name if is_host_module(name) else "")
    folder, sep, base = name.rpartition("/")
    if sep and module_path(f"{folder}/core").exists():
        return (folder, base != "core", base)
    return (name, False, "")


def host_path(host: str) -> Path:
    return HOSTS_DIR / host / "configuration.nix"


def imported(path: Path) -> list[str]:
    try:
        return hostfile.enabled(path.read_text(), path.parent, MODULES_DIR)
    except OSError:
        return []


def group_subs(core: str) -> list[str]:
    """The submodules a group's core.nix imports (for every host)."""
    return [n for n in imported(module_path(core)) if group_core(n) == core]


def load_state(host: str) -> dict:
    """{"modules": [...]}: the modules the host imports, and the submodules
    chosen in every group's core.nix (active only when the host imports
    that core)."""
    modules = imported(host_path(host))
    for core in filter(is_group, list_modules()):
        modules += [n for n in group_subs(core) if n not in modules]
    return {"modules": modules}


def updated_imports(path: Path, chosen: list[str]) -> str:
    return hostfile.update(path.read_text(), path.parent, MODULES_DIR, chosen,
                           lambda name: module_path(name).exists(), display_key)


def save_state(host: str, state: dict) -> None:
    """Write the host's own imports (submodules live in their core.nix)."""
    path = host_path(host)
    new = updated_imports(path, [n for n in state["modules"] if not group_core(n)])
    if new != path.read_text():
        path.write_text(new)


def core_text(core: str, subs: list[str]) -> str:
    """The core.nix of a group, importing exactly `subs`."""
    return updated_imports(module_path(core), subs)


def host_entries(host: str) -> list[modfile.Entry]:
    """The packages of the host's own environment.systemPackages list."""
    return [e for e in modfile.entries(host_path(host).read_text()) if e.editable]


def flake_args(host: str) -> list[str]:
    # The default host imports /etc/nixos/hardware-configuration.nix.
    return ["--impure"] if host == "default" else []


def nix_error(stderr: str) -> str:
    """The most useful line of a Nix error."""
    errors = [line.strip() for line in stderr.splitlines() if "error:" in line]
    return errors[-1] if errors else (stderr.strip().splitlines() or ["unknown error"])[-1]


def check_module(name: str) -> str | None:
    """Check a module file with Nix. Returns an error message, or None.

    The syntax is always checked; then the config of every host that uses
    the module is evaluated, which catches unknown package names.
    """
    path = module_path(name)
    proc = subprocess.run(["nix-instantiate", "--parse", str(path)],
                          capture_output=True, text=True)
    if proc.returncode != 0:
        return nix_error(proc.stderr)
    hosts = [name.removeprefix(HOST_PREFIX)] if is_host_module(name) else list_hosts()
    for host in hosts:
        if not is_active(name, load_state(host)["modules"]):
            continue
        proc = subprocess.run(
            ["nix", "eval", "--json", *flake_args(host),
             f"{DOTFILES}#nixosConfigurations.{host}.config.environment.systemPackages",
             "--apply", "map (p: p.name)"],
            capture_output=True, text=True,
        )
        if proc.returncode != 0:
            return f"{host}: {nix_error(proc.stderr)}"
    return None


def editor_command(path: Path, line: int | None = None) -> list[str]:
    editor = os.environ.get("EDITOR") or shutil.which("nvim") or "vi"
    if line is None:
        return [editor, str(path)]
    if Path(editor).name in ("hx", "helix"):
        return [editor, f"{path}:{line}"]
    return [editor, f"+{line}", str(path)]


def notify_desktop(summary: str, body: str, failed: bool) -> None:
    if shutil.which("notify-send"):
        subprocess.call(["notify-send", "--app-name=nixcfg", "--icon=nix-snowflake",
                         f"--urgency={'critical' if failed else 'normal'}",
                         summary, body])


def run_in_terminal(cmd: list[str], what: str, theme: Theme | None = None) -> None:
    """Run a command attached to the terminal, then wait for Enter.

    With a theme, the terminal takes its colors meanwhile. The window may have
    been closed meanwhile (nixcfg keeps running in tmux), so the result is
    also sent as a desktop notification.
    """
    if theme:
        print(terminal_palette(theme), end="")
    try:
        print(f"\n$ {' '.join(cmd)}\n", flush=True)
        code = subprocess.call(cmd, cwd=DOTFILES)
        status = "done" if code == 0 else f"failed (exit code {code})"
        notify_desktop(f"nixcfg: {what} {status}", " ".join(cmd), failed=code != 0)
        input(f"\n{status}. Press Enter to go back to nixcfg...")
    finally:
        if theme:
            print(TERMINAL_PALETTE_RESET, end="", flush=True)


def show_window() -> None:
    """Focus the nixcfg window, or open one attached to the session."""
    try:
        proc = subprocess.run(["hyprctl", "clients", "-j"], capture_output=True, text=True)
        clients = json.loads(proc.stdout)
    except (OSError, ValueError):
        clients = []
    for client in clients:
        if client.get("class") == "nixcfg":
            # Same as the SUPER + I bind in config/caelestia/hypr-user.lua.
            subprocess.run(["hyprctl", "eval", "hl.dispatch(hl.dsp.focus("
                            f'{{ window = "address:{client["address"]}" }}))'],
                           capture_output=True)
            return
    nixcfg = shutil.which("nixcfg")
    command = [nixcfg] if nixcfg else [sys.executable, str(Path(__file__).resolve())]
    # Without these, the new nixcfg would think it is already in the session.
    env = {k: v for k, v in os.environ.items() if k not in ("NIXCFG_SESSION", "TMUX", "TMUX_PANE")}
    subprocess.Popen(["kitty", "--class", "nixcfg", "--title", "nixcfg", *command],
                     env=env, start_new_session=True, stdin=subprocess.DEVNULL,
                     stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


