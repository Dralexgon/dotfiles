    def __init__(self) -> None:
        super().__init__()
        hosts = list_hosts()
        hostname = socket.gethostname()
        self.host = hostname if hostname in hosts else hosts[0]
        self.state = load_state(self.host)
        self.expanded: set[str] = set()  # groups shown open in the module list
        self.module: str | None = None  # module shown in the packages column
        self.entries: dict[int, modfile.Entry] = {}  # its packages, by line
        self.good: dict[Path, str] = {}  # last module text that passed the check
        self.check_status = ""
        self.jumping = False  # switching tabs to show a package's module
        self.tray = None
        self.terminal_theme = False  # t: the terminal's colors instead of nixcfg's

    def compose(self) -> ComposeResult:
        yield Static(id="titlebar")
        with TabbedContent(id="tabs"):
            with TabPane("Modules", id="modules-tab"):
                with Columns():
                    yield ModuleList(id="modules")
                    with Vertical(id="pkg-col"):
                        yield Static(id="pkg-title")
                        yield PackageList(id="module-packages")
                    with VerticalScroll(id="preview-col"):
                        yield Static(id="preview")
            with TabPane("Packages", id="packages-tab"):
                yield Input(id="filter", placeholder="Filter all packages (press /)")
                yield OptionList(id="all-packages")
        yield Footer(show_command_palette=False)

    def on_mount(self) -> None:
        self.scheme_mtime = -1.0
        self.load_theme()
        # Follow Caelestia when the wallpaper (and so the palette) changes.
        self.set_interval(2, self.load_theme)
        self.refresh_all()
        modules = self.query_one("#modules", ModuleList)
        modules.focus()
        modules.highlighted = 0
        if os.environ.get("NIXCFG_SESSION"):
            self.start_tray()

    def start_tray(self) -> None:
        """Show an icon in the bar while nixcfg runs in the background."""
        try:
            import tray
        except ImportError:  # dbus-fast is missing until the next rebuild
            return
        self.tray = tray.Tray(on_open=show_window,
                              on_quit=lambda: self.call_from_thread(self.exit))
        self.tray.start()

    def run_command(self, cmd: list[str], what: str) -> None:
        if self.tray:
            self.tray.set_busy(f"{what.capitalize()} running…")
        try:
            theme = None if self.terminal_theme else self.current_theme
            with self.suspend():
                run_in_terminal(cmd, what, theme)
        finally:
            if self.tray:
                self.tray.set_busy("")

