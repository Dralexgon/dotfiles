class Generations(ModalScreen[list[int] | None]):
    """Pick system generations to delete. The current one can't be."""
    BINDINGS = [
        Binding("escape", "dismiss(None)", "Cancel"),
        Binding("o", "select_older", "Older"),
        Binding("d", "delete", "Delete"),
    ]

    def __init__(self, generations: list[dict]) -> None:
        super().__init__()
        self.generations = generations

    def compose(self) -> ComposeResult:
        selections = []
        for g in self.generations:
            tags = [t for t in ("current", "running") if g[t]]
            prompt = (f"{g['number']:>4}  {g['date']:%Y-%m-%d %H:%M}  {g['version']}"
                      f"  linux {g['kernel']}")
            if tags:
                prompt += f"  [b]({', '.join(tags)})[/b]"
            selections.append(Selection(prompt, g["number"], disabled=g["current"]))
        with Vertical(classes="dialog wide"):
            yield Label("System generations to delete")
            yield SelectionList[int](*selections, id="generations")
            yield Label("[b]space[/b] select   [b]o[/b] select all older   "
                        "[b]d[/b] delete selected   [b]esc[/b] cancel", classes="hint")

    def action_select_older(self) -> None:
        listing = self.query_one("#generations", SelectionList)
        if listing.highlighted is None:
            return
        for index in range(listing.highlighted + 1, listing.option_count):
            option = listing.get_option_at_index(index)
            if not option.disabled:
                listing.select(option)

    def action_delete(self) -> None:
        self.dismiss(sorted(self.query_one("#generations", SelectionList).selected))


class PackageSearch(ModalScreen[str | None]):
    """Search the flake's locked nixpkgs and return an attribute path."""

    BINDINGS = [Binding("escape", "dismiss(None)", "Cancel")]

    def __init__(self, target: str) -> None:
        super().__init__()
        self.target = target

    def compose(self) -> ComposeResult:
        with Vertical(classes="dialog wide"):
            yield Label(f"Add a package to {escape(self.target)}: type a search and press Enter")
            yield Input(placeholder="e.g. firefox, or kdePackages.kate")
            yield Label("", id="status", classes="hint")
            yield OptionList(id="results")

    @on(Input.Submitted)
    def search(self, event: Input.Submitted) -> None:
        query = event.value.strip()
        if not query:
            return
        results = self.query_one("#results", OptionList)
        results.clear_options()
        results.add_option(Option(f"Add [b]{escape(query)}[/b] as-is", id=query))
        # Enter again adds the typed name; search results show up below it.
        results.focus()
        results.highlighted = 0
        self.query_one("#status", Label).update(
            "Searching nixpkgs... (the first search can take a minute)"
        )
        self.run_search(query)

    @work(thread=True, exclusive=True)
    def run_search(self, query: str) -> None:
        cmd = ["nix", "search", "--inputs-from", str(DOTFILES), "nixpkgs",
               *query.split(), "--json"]
        proc = subprocess.run(cmd, capture_output=True, text=True)
        try:
            found = json.loads(proc.stdout or "{}")
        except json.JSONDecodeError:
            found = {}
        error = "" if proc.returncode == 0 else nix_error(proc.stderr)
        self.app.call_from_thread(self.show_results, found, error)

    def show_results(self, found: dict, error: str) -> None:
        results = self.query_one("#results", OptionList)
        options = []
        for key, info in list(found.items())[:200]:
            # "legacyPackages.x86_64-linux.kdePackages.kate" -> "kdePackages.kate"
            attr = key.split(".", 2)[2]
            desc = escape(info.get("description") or "")
            prompt = f"[b]{escape(attr)}[/b] [dim]{escape(info.get('version', ''))}[/dim]  {desc}"
            if attr == self.query_one(Input).value.strip():
                # The exact name typed: describe the "as-is" entry instead.
                results.replace_option_prompt(attr, prompt)
            else:
                options.append(Option(prompt, id=attr))
        results.add_options(options)
        status = self.query_one("#status", Label)
        if error:
            status.update(f"[$error]nix search failed:[/] {escape(error)}")
        else:
            more = " (showing 200)" if len(found) > 200 else ""
            status.update(f"{len(found)} result(s){more}")

    @on(OptionList.OptionSelected)
    def choose(self, event: OptionList.OptionSelected) -> None:
        self.dismiss(event.option_id)


