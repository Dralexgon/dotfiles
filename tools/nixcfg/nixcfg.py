    def load_theme(self) -> None:
        try:
            mtime = CAELESTIA_SCHEME.stat().st_mtime
        except OSError:
            mtime = None
        if mtime == self.scheme_mtime:
            return
        self.scheme_mtime = mtime
        theme = caelestia_theme()
        if self.terminal_theme:
            self.theme = TERMINAL_THEMES[theme.dark if theme else True]
        elif theme:
            self.register_theme(theme)
            if self.theme == "caelestia":
                # Same name, new colors: setting it again wouldn't restyle.
                self.mutate_reactive(App.theme)
            else:
                self.theme = "caelestia"
        elif self.theme != FALLBACK_THEME:
            self.theme = FALLBACK_THEME
        self.show_preview(self.highlighted_line())  # its colors are baked in

    def action_toggle_theme(self) -> None:
        self.terminal_theme = not self.terminal_theme
        self.scheme_mtime = -1.0  # makes load_theme apply it now
        self.load_theme()
        self.notify("Terminal colors" if self.terminal_theme else "nixcfg colors")

    def refresh_all(self) -> None:
        title = f"[b $primary]nixcfg[/]  [dim]•[/]  [b]{escape(self.host)}[/]"
        if self.host == socket.gethostname():
            title += "  [dim]this machine[/]"
        self.query_one("#titlebar", Static).update(title)
        self.refresh_modules()
        self.refresh_all_packages()

    def module_names(self) -> list[str]:
        return sorted({CORE, host_module(self.host), *list_modules(), *self.state["modules"]},
                      key=display_key)

    def refresh_modules(self) -> None:
        others = {h: load_state(h)["modules"] for h in list_hosts() if h != self.host}
        enabled = self.state["modules"]
        on_disk = list_modules()
        names = self.module_names()
        visible = [n for n in names if group_core(n) in (None, *self.expanded)]

        modules = self.query_one("#modules", ModuleList)
        current = self.highlighted_module()
        modules.clear_options()
        selections = []
        for i, name in enumerate(visible):
            core = group_core(name)
            if core:
                # Submodule: drawn as a branch of its group, dimmed when the group is off.
                last = i + 1 == len(visible) or group_core(visible[i + 1]) != core
                label = f"  [dim]{'└─' if last else '├─'}[/] {escape(name.rsplit('/', 1)[1])}"
                if core not in enabled:
                    label = f"[dim]{label}[/]"
            elif is_group(name):
                subs = [n for n in names if group_core(n) == name]
                on = sum(n in enabled for n in subs)
                arrow = "▾" if name in self.expanded else "▸"
                label = f"{escape(name.removesuffix('/core'))}  [dim]{on}/{len(subs)} {arrow}[/]"
            else:
                label = escape(name)
            if name == CORE:
                label = f"{escape(name)}  [dim]nixos/core.nix · every host[/]"
                selections.append(Selection(label, name, True))
                continue
            if is_host_module(name):
                rel = module_path(name).relative_to(DOTFILES).as_posix()
                label = f"configuration  [dim]{escape(rel)} · this host[/]"
                selections.append(Selection(label, name, True))
                continue
            if name not in on_disk:
                label += "  [$error]missing file[/]"
            used_by = [h for h, mods in others.items() if is_active(name, mods)]
            if used_by:
                label += f"  [dim]{' · '.join(used_by)}[/]"
            selections.append(Selection(label, name, name in enabled))
        modules.add_options(selections)
        if current in visible:
            modules.highlighted = visible.index(current)
        elif group_core(current or "") in visible:
            modules.highlighted = visible.index(group_core(current))

        tabs = self.query_one("#tabs", TabbedContent)
        count = f"{sum(is_active(n, enabled) for n in names)}/{len(names)}"
        tabs.get_tab("modules-tab").label = f"Modules [dim]{count}[/]"

    def show_module(self, name: str | None, line: int | None = None) -> None:
        """Fill the packages and preview columns for a module."""
        self.module = name
        packages = self.query_one("#module-packages", PackageList)
        current = line if line is not None else self.highlighted_line()
        packages.clear_options()
        self.entries = {}
        if not name or not module_path(name).exists():
            self.query_one("#pkg-title", Static).update(
                "[dim]no file[/]" if name else "")
            self.query_one("#preview", Static).update("")
            return
        selections = []
        for entry in module_entries(name):
            self.entries[entry.line] = entry
            if entry.editable:
                label = escape(entry.name)
                if entry.comment:
                    label += f"  [dim]{escape(entry.comment)}[/]"
            else:
                label = f"[dim i]{escape(entry.name)}[/]"
            selections.append(Selection(label, entry.line, entry.enabled,
                                        disabled=not entry.editable))
        packages.add_options(selections)
        lines = list(self.entries)
        if current in lines:
            packages.highlighted = lines.index(current)
        self.update_package_title()
        self.show_preview(current if current in lines else None)

    def update_package_title(self) -> None:
        if not self.module:
            return
        on = sum(e.enabled for e in self.entries.values())
        title = f"[b]{escape(module_path(self.module).name)}[/]  [dim]{on}/{len(self.entries)}[/]"
        if self.check_status:
            title += f"  {self.check_status}"
        self.query_one("#pkg-title", Static).update(title)

    def show_preview(self, line: int | None) -> None:
        if not self.module or not module_path(self.module).exists():
            return
        syntax = Syntax(
            module_path(self.module).read_text(), "nix",
            theme="ansi_dark" if self.current_theme.dark else "ansi_light",
            line_numbers=True, word_wrap=False,
            highlight_lines={line + 1} if line is not None else set(),
            # The terminal themes' "ansi_default" is "default" for Rich.
            background_color=(self.current_theme.background or "default").removeprefix("ansi_"),
        )
        self.query_one("#preview", Static).update(syntax)
        column = self.query_one("#preview-col", VerticalScroll)
        target = 0 if line is None else max(0, line - column.size.height // 2)
        self.call_after_refresh(column.scroll_to, y=target, animate=False)

    def refresh_all_packages(self) -> None:
        """The flat list of every package: this host's and every module's."""
        enabled = self.state["modules"]
        query = self.query_one("#filter", Input).value.strip().lower()
        rows = [(e.name, "this host", e.enabled, f"h:{e.line}") for e in host_entries(self.host)]
        for module in self.module_names():
            if is_host_module(module):  # already listed as "this host"
                continue
            active = is_active(module, enabled)
            for entry in module_entries(module):
                if entry.editable:
                    rows.append((entry.name, f"{module}.nix", active and entry.enabled,
                                 f"m:{module}:{entry.line}"))
        rows.sort(key=lambda r: (r[0].lower(), r[1]))

        listing = self.query_one("#all-packages", OptionList)
        current = listing.highlighted_option.id if listing.highlighted_option else None
        listing.clear_options()
        options = []
        for name, where, installed, key in rows:
            if query and query not in name.lower() and query not in where.lower():
                continue
            dot = "[$primary]●[/]" if installed else "[dim]○[/]"
            text = escape(name) if installed else f"[dim]{escape(name)}[/]"
            padding = " " * max(2, 36 - len(name))
            options.append(Option(f"{dot} {text}{padding}[dim]{escape(where)}[/]", id=key))
        listing.add_options(options)
        ids = [o.id for o in options]
        if current in ids:
            listing.highlighted = ids.index(current)

        installed = sum(r[2] for r in rows)
        self.query_one("#tabs", TabbedContent).get_tab("packages-tab").label = (
            f"Packages [dim]{installed}[/]"
        )

    def highlighted_module(self) -> str | None:
        modules = self.query_one("#modules", ModuleList)
        if modules.highlighted is None or modules.highlighted >= modules.option_count:
            return None
        return modules.get_option_at_index(modules.highlighted).value

    def highlighted_line(self) -> int | None:
        packages = self.query_one("#module-packages", PackageList)
        if packages.highlighted is None or packages.highlighted >= packages.option_count:
            return None
        return packages.get_option_at_index(packages.highlighted).value

    def focused_id(self) -> str | None:
        return self.focused.id if self.focused else None

    def check_action(self, action: str, parameters) -> bool | None:
        if isinstance(self.screen, ModalScreen):
            return False
        if not self.is_mounted:
            return True
        modules_tab = self.query_one("#tabs", TabbedContent).active == "modules-tab"
        focus = self.focused_id()
        if action == "delete_module":
            return (modules_tab and focus == "modules"
                    and not is_pinned(self.highlighted_module() or CORE))
        if action == "new_module":
            return modules_tab and focus == "modules"
        if action == "edit":
            return modules_tab
        if action == "add_package":
            return focus == "module-packages" or not modules_tab
        if action == "remove_package":
            if focus == "module-packages":
                entry = self.entries.get(self.highlighted_line())
                return bool(entry and entry.editable)
            listing = self.query_one("#all-packages", OptionList)
            option = listing.highlighted_option
            return not modules_tab and bool(option and option.id.startswith("h:"))
        if action == "focus_filter":
            return not modules_tab
        return True

