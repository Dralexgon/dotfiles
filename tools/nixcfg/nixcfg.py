"""nixcfg: a TUI to enable/disable/add/remove modules and packages of the
NixOS hosts in ~/dotfiles.

Everything it edits is plain data: nixos/hosts/<host>/state.json, which
nixos/state.nix turns into imports and environment.systemPackages.
Module files themselves are only created (from a template) or deleted.
"""

import json
import os
import re
import shutil
import socket
import subprocess
import sys
from pathlib import Path

from rich.markup import escape
from textual import on, work
from textual.app import App, ComposeResult
from textual.binding import Binding
from textual.containers import Vertical
from textual.screen import ModalScreen
from textual.theme import Theme
from textual.widgets import (
    Footer,
    Input,
    Label,
    OptionList,
    SelectionList,
    Static,
    TabbedContent,
    TabPane,
)
from textual.widgets._toggle_button import ToggleButton
from textual.widgets.option_list import Option
from textual.widgets.selection_list import Selection

DOTFILES = Path(os.environ.get("NIXCFG_DOTFILES", Path.home() / "dotfiles"))
HOSTS_DIR = DOTFILES / "nixos" / "hosts"
MODULES_DIR = DOTFILES / "nixos" / "modules"

# A module is any .nix file under nixos/modules, named by its path without .nix
# ("gaming", "epita/core", "epita/c").
MODULE_NAME = re.compile(r"^[A-Za-z0-9_-]+(/[A-Za-z0-9_-]+)*$")

MODULE_TEMPLATE = """\
{ pkgs, ... }:

{
  environment.systemPackages = with pkgs; [
  ];
}
"""

# Material You colors generated by Caelestia from the wallpaper.
CAELESTIA_SCHEME = Path.home() / ".local/state/caelestia/scheme.json"
FALLBACK_THEME = "catppuccin-mocha"

# SelectionList draws its toggles with ToggleButton's glyphs: use a plain dot.
ToggleButton.BUTTON_LEFT = " "
ToggleButton.BUTTON_INNER = "●"
ToggleButton.BUTTON_RIGHT = " "


def caelestia_theme() -> Theme | None:
    try:
        scheme = json.loads(CAELESTIA_SCHEME.read_text())
        c = {k: f"#{v}" for k, v in scheme["colours"].items()}
        return Theme(
            name="caelestia",
            dark=scheme.get("mode", "dark") == "dark",
            primary=c["primary"],
            secondary=c["secondary"],
            accent=c["tertiary"],
            error=c["error"],
            warning=c.get("term3", c["tertiary"]),
            success=c.get("term2", c["secondary"]),
            foreground=c["onSurface"],
            background=c["background"],
            surface=c["surfaceContainerLow"],
            panel=c["surfaceContainer"],
        )
    except (OSError, KeyError, ValueError):
        return None


def list_hosts() -> list[str]:
    return sorted(p.parent.name for p in HOSTS_DIR.glob("*/state.json"))


def list_modules() -> list[str]:
    return sorted(
        p.relative_to(MODULES_DIR).with_suffix("").as_posix()
        for p in MODULES_DIR.rglob("*.nix")
    )


def module_path(name: str) -> Path:
    return MODULES_DIR / f"{name}.nix"


# A folder with a core.nix is a group (same rule as nixos/state.nix): its core
# switches the whole group, and each submodule is toggled on its own.
def group_core(name: str) -> str | None:
    """The core of the group a submodule is in ("epita/c" -> "epita/core")."""
    folder, sep, _ = name.rpartition("/")
    core = f"{folder}/core"
    if not sep or name == core or not module_path(core).exists():
        return None
    return core


def is_active(name: str, enabled: list[str]) -> bool:
    core = group_core(name)
    return name in enabled and (core is None or core in enabled)


def display_key(name: str) -> tuple:
    """Sort groups by folder name, with their submodules right after them."""
    folder, sep, base = name.rpartition("/")
    if sep and module_path(f"{folder}/core").exists():
        return (folder, base != "core", base)
    return (name, False, "")


def state_path(host: str) -> Path:
    return HOSTS_DIR / host / "state.json"


def load_state(host: str) -> dict:
    state = json.loads(state_path(host).read_text())
    state.setdefault("modules", [])
    state.setdefault("packages", [])
    return state


def save_state(host: str, state: dict) -> None:
    state_path(host).write_text(json.dumps(state, indent=2) + "\n")


def flake_args(host: str) -> list[str]:
    # The default host imports /etc/nixos/hardware-configuration.nix.
    return ["--impure"] if host == "default" else []


def run_in_terminal(cmd: list[str]) -> None:
    """Run a command attached to the terminal, then wait for Enter."""
    print(f"\n$ {' '.join(cmd)}\n", flush=True)
    code = subprocess.call(cmd, cwd=DOTFILES)
    status = "done" if code == 0 else f"failed (exit code {code})"
    input(f"\n{status}. Press Enter to go back to nixcfg...")


class TextPrompt(ModalScreen[str | None]):
    BINDINGS = [Binding("escape", "dismiss(None)", "Cancel")]

    def __init__(self, title: str, placeholder: str = "") -> None:
        super().__init__()
        self.title_text = title
        self.placeholder = placeholder

    def compose(self) -> ComposeResult:
        with Vertical(classes="dialog"):
            yield Label(self.title_text)
            yield Input(placeholder=self.placeholder)

    @on(Input.Submitted)
    def submit(self, event: Input.Submitted) -> None:
        self.dismiss(event.value.strip() or None)


class Confirm(ModalScreen[bool]):
    BINDINGS = [
        Binding("y", "dismiss(True)", "Yes"),
        Binding("n,escape", "dismiss(False)", "No"),
    ]

    def __init__(self, question: str) -> None:
        super().__init__()
        self.question = question

    def compose(self) -> ComposeResult:
        with Vertical(classes="dialog"):
            yield Label(self.question)
            yield Label("[b]y[/b] yes   [b]n[/b] no", classes="hint")


class Choose(ModalScreen[str | None]):
    BINDINGS = [Binding("escape", "dismiss(None)", "Cancel")]

    def __init__(self, title: str, choices: list[str]) -> None:
        super().__init__()
        self.title_text = title
        self.choices = choices

    def compose(self) -> ComposeResult:
        with Vertical(classes="dialog"):
            yield Label(self.title_text)
            yield OptionList(*[Option(c, id=c) for c in self.choices])

    @on(OptionList.OptionSelected)
    def choose(self, event: OptionList.OptionSelected) -> None:
        self.dismiss(event.option_id)


class PackageSearch(ModalScreen[str | None]):
    """Search the flake's locked nixpkgs and return an attribute path."""

    BINDINGS = [Binding("escape", "dismiss(None)", "Cancel")]

    def compose(self) -> ComposeResult:
        with Vertical(classes="dialog wide"):
            yield Label("Add a package: type a search and press Enter")
            yield Input(placeholder="e.g. firefox, or kdePackages.kate")
            yield Label("", id="status", classes="hint")
            yield OptionList(id="results")

    @on(Input.Submitted)
    def search(self, event: Input.Submitted) -> None:
        query = event.value.strip()
        if not query:
            return
        results = self.query_one("#results", OptionList)
        results.clear_options()
        results.add_option(Option(f"Add [b]{escape(query)}[/b] as-is", id=query))
        self.query_one("#status", Label).update(
            "Searching nixpkgs... (the first search can take a minute)"
        )
        self.run_search(query)

    @work(thread=True, exclusive=True)
    def run_search(self, query: str) -> None:
        cmd = ["nix", "search", "--inputs-from", str(DOTFILES), "nixpkgs",
               *query.split(), "--json"]
        proc = subprocess.run(cmd, capture_output=True, text=True)
        try:
            found = json.loads(proc.stdout or "{}")
        except json.JSONDecodeError:
            found = {}
        error = "" if proc.returncode == 0 else proc.stderr.strip().splitlines()[-1:]
        self.app.call_from_thread(self.show_results, found, error)

    def show_results(self, found: dict, error) -> None:
        results = self.query_one("#results", OptionList)
        options = []
        for key, info in list(found.items())[:200]:
            # "legacyPackages.x86_64-linux.kdePackages.kate" -> "kdePackages.kate"
            attr = key.split(".", 2)[2]
            desc = escape(info.get("description") or "")
            prompt = f"[b]{escape(attr)}[/b] [dim]{escape(info.get('version', ''))}[/dim]  {desc}"
            if attr == self.query_one(Input).value.strip():
                # The exact name typed: describe the "as-is" entry instead.
                results.replace_option_prompt(attr, prompt)
            else:
                options.append(Option(prompt, id=attr))
        results.add_options(options)
        status = self.query_one("#status", Label)
        if error:
            status.update(f"[$error]nix search failed:[/] {escape(error[0])}")
        else:
            more = " (showing 200)" if len(found) > 200 else ""
            status.update(f"{len(found)} result(s){more}")
        results.focus()

    @on(OptionList.OptionSelected)
    def choose(self, event: OptionList.OptionSelected) -> None:
        self.dismiss(event.option_id)


class NixCfg(App):
    TITLE = "nixcfg"
    CSS = """
    Screen { background: $background; }

    #titlebar { height: 1; padding: 0 2; margin-top: 1; }

    TabbedContent { margin: 0 1; height: 1fr; }
    ContentSwitcher, TabPane { height: 1fr; }
    Tabs { background: $background; }
    Tab { color: $text-muted; }
    Tab.-active { color: $primary; text-style: bold; }
    Underline > .underline--bar { background: $foreground 8%; color: $primary; }
    TabPane { padding: 1 0 0 0; }

    OptionList, OptionList:focus {
        height: 1fr; border: none; padding: 0 1;
        background: $background; background-tint: transparent;
        scrollbar-size-vertical: 1;
        scrollbar-background: $background;
        scrollbar-color: $primary 30%;
        scrollbar-color-hover: $primary 50%;
        scrollbar-color-active: $primary;
    }
    OptionList > .option-list--option { padding: 0 1; }
    OptionList > .option-list--option-highlighted,
    OptionList:focus > .option-list--option-highlighted {
        background: $primary 15%; color: $primary; text-style: bold;
    }
    OptionList > .option-list--option-hover { background: $foreground 5%; }

    SelectionList > .selection-list--button,
    SelectionList > .selection-list--button-highlighted {
        background: transparent; color: $foreground 25%; text-style: none;
    }
    SelectionList > .selection-list--button-selected,
    SelectionList > .selection-list--button-selected-highlighted {
        background: transparent; color: $primary; text-style: bold;
    }

    Footer { background: $background; padding: 0 1; }
    Footer > FooterKey { background: $background; color: $text-muted; }
    Footer > FooterKey .footer-key--key { background: $background; color: $primary; }
    FooterKey:hover { background: $primary 15%; }

    ModalScreen { align: center middle; background: $background 60%; }
    .dialog {
        width: 64; height: auto; max-height: 80%;
        padding: 1 2; border: round $primary 60%; background: $panel;
    }
    .dialog.wide { width: 90%; height: 80%; }
    .dialog OptionList, .dialog OptionList:focus { background: $panel; padding: 0; }
    .dialog > Label { color: $primary; text-style: bold; margin-bottom: 1; }
    .dialog > Label.hint { color: $text-muted; text-style: none; margin: 1 0 0 0; }
    Input, Input:focus {
        border: round $foreground 20%; background: $panel; padding: 0 1;
    }
    Input:focus { border: round $primary; }
    #results { height: 1fr; margin-top: 1; }
    """
    BINDINGS = [
        Binding("h", "switch_host", "Host"),
        Binding("n", "new_module", "New module"),
        Binding("e", "edit_module", "Edit module"),
        Binding("D", "delete_module", "Delete module"),
        Binding("a", "add_package", "Add package"),
        Binding("x,delete", "remove_package", "Remove package"),
        Binding("g", "git_diff", "Diff"),
        Binding("b", "build", "Build"),
        Binding("r", "rebuild", "Switch"),
        Binding("q", "quit", "Quit"),
    ]

    MODULE_ACTIONS = {"new_module", "edit_module", "delete_module"}
    PACKAGE_ACTIONS = {"add_package", "remove_package"}

    def __init__(self) -> None:
        super().__init__()
        hosts = list_hosts()
        hostname = socket.gethostname()
        self.host = hostname if hostname in hosts else hosts[0]
        self.state = load_state(self.host)

    def compose(self) -> ComposeResult:
        yield Static(id="titlebar")
        with TabbedContent(id="tabs"):
            with TabPane("Modules", id="modules-tab"):
                yield SelectionList[str](id="modules")
            with TabPane("Packages", id="packages-tab"):
                yield OptionList(id="packages")
        yield Footer(show_command_palette=False)

    def on_mount(self) -> None:
        self.scheme_mtime = -1.0
        self.load_theme()
        # Follow Caelestia when the wallpaper (and so the palette) changes.
        self.set_interval(2, self.load_theme)
        self.refresh_lists()
        modules = self.query_one("#modules", SelectionList)
        modules.focus()
        modules.highlighted = 0

    # Display

    def load_theme(self) -> None:
        try:
            mtime = CAELESTIA_SCHEME.stat().st_mtime
        except OSError:
            mtime = None
        if mtime == self.scheme_mtime:
            return
        self.scheme_mtime = mtime
        theme = caelestia_theme()
        if theme:
            self.register_theme(theme)
            self.theme = "caelestia"
        elif self.theme != FALLBACK_THEME:
            self.theme = FALLBACK_THEME

    def refresh_lists(self) -> None:
        title = f"[b $primary]nixcfg[/]  [dim]•[/]  [b]{escape(self.host)}[/]"
        if self.host == socket.gethostname():
            title += "  [dim]this machine[/]"
        self.query_one("#titlebar", Static).update(title)

        others = {h: load_state(h)["modules"] for h in list_hosts() if h != self.host}
        enabled = self.state["modules"]
        on_disk = list_modules()
        names = sorted(set(on_disk) | set(enabled), key=display_key)

        modules = self.query_one("#modules", SelectionList)
        highlighted = modules.highlighted
        modules.clear_options()
        selections = []
        for i, name in enumerate(names):
            core = group_core(name)
            if core:
                # Submodule: drawn as a branch of its group, dimmed when the group is off.
                last = i + 1 == len(names) or group_core(names[i + 1]) != core
                label = f"  [dim]{'└─' if last else '├─'}[/] {escape(name.rsplit('/', 1)[1])}"
                if core not in enabled:
                    label = f"[dim]{label}[/]"
            elif name.endswith("/core") and module_path(name).exists():
                folder = name.removesuffix("/core")
                subs = [n for n in names if group_core(n) == name]
                on = sum(n in enabled for n in subs)
                label = f"{escape(folder)}  [dim]{on}/{len(subs)}[/]"
            else:
                label = escape(name)
            if name not in on_disk:
                label += "  [$error]missing file[/]"
            used_by = [h for h, mods in others.items() if is_active(name, mods)]
            if used_by:
                label += f"  [dim]{' · '.join(used_by)}[/]"
            selections.append(Selection(label, name, name in enabled))
        modules.add_options(selections)
        if highlighted is not None and selections:
            modules.highlighted = min(highlighted, len(selections) - 1)

        tabs = self.query_one("#tabs", TabbedContent)
        count = f"{sum(is_active(n, enabled) for n in names)}/{len(names)}"
        tabs.get_tab("modules-tab").label = f"Modules [dim]{count}[/]"
        tabs.get_tab("packages-tab").label = (
            f"Packages [dim]{len(self.state['packages'])}[/]"
        )

        packages = self.query_one("#packages", OptionList)
        highlighted = packages.highlighted
        packages.clear_options()
        packages.add_options([Option(escape(p), id=p) for p in self.state["packages"]])
        if highlighted is not None and self.state["packages"]:
            packages.highlighted = min(highlighted, len(self.state["packages"]) - 1)

    def check_action(self, action: str, parameters) -> bool | None:
        if isinstance(self.screen, ModalScreen):
            return False
        tab = self.query_one("#tabs", TabbedContent).active
        if action in self.MODULE_ACTIONS:
            return tab == "modules-tab"
        if action in self.PACKAGE_ACTIONS:
            return tab == "packages-tab"
        return True

    @on(TabbedContent.TabActivated)
    def tab_changed(self, event: TabbedContent.TabActivated) -> None:
        widget = event.pane.query_one(OptionList)
        widget.focus()
        if widget.highlighted is None and widget.option_count:
            widget.highlighted = 0
        self.refresh_bindings()

    def highlighted_module(self) -> str | None:
        modules = self.query_one("#modules", SelectionList)
        if modules.highlighted is None:
            return None
        return modules.get_option_at_index(modules.highlighted).value

    def save(self) -> None:
        save_state(self.host, self.state)

    # Modules

    @on(SelectionList.SelectionToggled)
    def module_toggled(self, event: SelectionList.SelectionToggled) -> None:
        selected = set(event.selection_list.selected)
        # Keep the existing order, append newly enabled modules at the end.
        kept = [m for m in self.state["modules"] if m in selected]
        added = sorted(selected - set(kept))
        self.state["modules"] = kept + added
        self.save()
        self.refresh_lists()

    def action_new_module(self) -> None:
        def create(name: str | None) -> None:
            if not name:
                return
            name = name.removesuffix(".nix")
            if not MODULE_NAME.match(name):
                self.notify("Use a name like 'gaming' or 'folder/name'.", severity="error")
                return
            path = module_path(name)
            if path.exists():
                self.notify(f"{path.name} already exists.", severity="error")
                return
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(MODULE_TEMPLATE)
            # Flakes only see files tracked by git.
            subprocess.run(["git", "-C", str(DOTFILES), "add", str(path)])
            self.state["modules"].append(name)
            self.save()
            self.refresh_lists()
            self.open_editor(path)

        self.push_screen(TextPrompt("New module name", "e.g. music or epita/rust"), create)

    def action_edit_module(self) -> None:
        name = self.highlighted_module()
        if name and module_path(name).exists():
            self.open_editor(module_path(name))

    def open_editor(self, path: Path) -> None:
        editor = os.environ.get("EDITOR") or shutil.which("nvim") or "vi"
        with self.suspend():
            subprocess.call([editor, str(path)])
        self.refresh_lists()

    def action_delete_module(self) -> None:
        name = self.highlighted_module()
        if not name:
            return
        path = module_path(name)
        hosts = [h for h in list_hosts() if name in load_state(h)["modules"]]
        importers = [
            p.relative_to(MODULES_DIR).as_posix()
            for p in MODULES_DIR.rglob("*.nix")
            if p != path and f"/{path.name}" in p.read_text()
        ]
        question = f"Delete module [b]{escape(name)}[/b] ({path.name})?"
        if hosts:
            question += f"\nIt will be disabled on: {', '.join(hosts)}."
        if any(group_core(n) == name for n in list_modules()):
            question += "\nIts submodules stay, but are no longer grouped."
        if importers:
            question += f"\n[$warning]Warning:[/] mentioned in {', '.join(importers)}."

        def delete(yes: bool) -> None:
            if not yes:
                return
            for host in hosts:
                state = self.state if host == self.host else load_state(host)
                state["modules"].remove(name)
                save_state(host, state)
            path.unlink(missing_ok=True)
            if path.parent != MODULES_DIR and not any(path.parent.iterdir()):
                path.parent.rmdir()
            subprocess.run(["git", "-C", str(DOTFILES), "rm", "-q", "--cached",
                            "--ignore-unmatch", str(path)])
            self.refresh_lists()
            self.notify(f"Deleted {path.name}.")

        self.push_screen(Confirm(question), delete)

    # Packages

    def action_add_package(self) -> None:
        def add(attr: str | None) -> None:
            if not attr:
                return
            if attr in self.state["packages"]:
                self.notify(f"{attr} is already installed.")
                return
            self.state["packages"].append(attr)
            self.save()
            self.refresh_lists()
            self.notify(f"Added {attr}.")

        self.push_screen(PackageSearch(), add)

    def action_remove_package(self) -> None:
        packages = self.query_one("#packages", OptionList)
        if packages.highlighted is None:
            return
        attr = packages.get_option_at_index(packages.highlighted).id
        self.state["packages"].remove(attr)
        self.save()
        self.refresh_lists()
        self.notify(f"Removed {attr}.")

    # Host and system

    def action_switch_host(self) -> None:
        def switch(host: str | None) -> None:
            if host:
                self.host = host
                self.state = load_state(host)
                self.refresh_lists()

        self.push_screen(Choose("Host to edit", list_hosts()), switch)

    def action_git_diff(self) -> None:
        with self.suspend():
            subprocess.call(["git", "-C", str(DOTFILES), "diff", "HEAD", "--", "nixos"])

    def action_build(self) -> None:
        attr = f"{DOTFILES}#nixosConfigurations.{self.host}.config.system.build.toplevel"
        with self.suspend():
            run_in_terminal(["nix", "build", "--no-link", *flake_args(self.host), attr])

    def action_rebuild(self) -> None:
        if self.host != socket.gethostname():
            self.notify(
                f"This machine is {socket.gethostname()}, not {self.host}: "
                "use Build (b) to test it instead.",
                severity="error",
            )
            return

        def rebuild(yes: bool) -> None:
            if yes:
                with self.suspend():
                    run_in_terminal(["sudo", "nixos-rebuild", "switch",
                                     *flake_args(self.host),
                                     "--flake", f"{DOTFILES}#{self.host}"])

        self.push_screen(Confirm(f"Run nixos-rebuild switch for {self.host}?"), rebuild)


def main() -> None:
    if not list_hosts():
        sys.exit(f"No nixos/hosts/*/state.json found in {DOTFILES} (set NIXCFG_DOTFILES).")
    NixCfg().run()


if __name__ == "__main__":
    main()
